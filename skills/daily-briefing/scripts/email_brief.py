def esc(value) -> str:
    return html.escape(str(value or ""), quote=True)


def para(text: str) -> str:
    out = esc(text)
    out = re.sub(r"^Proposal:", "<strong>Proposal:</strong>", out)
    return re.sub(r"(\[\d+(?:[-\u2013,]\s?\d+)*\])", r'<span style="color:#6b7280;">\1</span>', out)


def extract(raw: str):
    start, end = raw.find("{"), raw.rfind("}")
    if start == -1 or end <= start:
        return None
    try:
        data = json.loads(raw[start : end + 1])
    except json.JSONDecodeError:
        return None
    return data if isinstance(data, dict) and data.get("headline") else None


# Australian Government Email Protective Marking Standard 2025 (EPMS). Only markings that
# may travel over a commercial email API are accepted; PROTECTED and above are refused.
EPMS_VERSION = "2025.1"
MARKINGS = ("UNOFFICIAL", "OFFICIAL", "OFFICIAL:Sensitive")


def body_marking(marking: str) -> str:
    """The text marking for the body. EPMS writes OFFICIAL:Sensitive with a space there."""
    return marking.replace(":Sensitive", ": Sensitive")


def marked_subject(subject: str, marking: str | None) -> str:
    """EPMS 7.1: the marking goes at the end of the subject."""
    return f"{subject} [SEC={marking}]" if marking else subject


def marking_header(marking: str, origin: str) -> str:
    """EPMS 7.2: the X-Protective-Marking value, elements in the required order."""
    return f"VER={EPMS_VERSION}, NS=gov.au, SEC={marking}, ORIGIN={origin}"


def address(sender: str) -> str:
    """The bare address in 'Name <addr>' or 'addr'."""
    match = re.search(r"<([^<>]+)>\s*$", sender)
    return (match.group(1) if match else sender).strip()


def marking_bar(marking: str | None) -> str:
    if not marking:
        return ""
    return (
        '<tr><td align="center" style="padding:6px 12px;font-size:12px;font-weight:700;'
        f'letter-spacing:1px;color:#111827;background:#f9fafb;">{esc(body_marking(marking))}</td></tr>'
    )


