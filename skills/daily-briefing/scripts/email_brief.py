# The groups the intel store's vulnerability digest adds, in the order they are shown. They
# come first, ahead of the user's own watches.
DIGEST_GROUPS = (
    "Public exploits",
    "Malicious packages",
    "Critical and high vulnerabilities",
    "Live incidents",
    "Your dependencies",
)


def load_watches(path: str | None) -> list[dict]:
    """Watch hits from `cyberau-mcp store watchlist hits`. A missing or bad file is no hits."""
    if not path:
        return []
    try:
        raw = open(path, encoding="utf-8").read()
        payload = json.loads(raw[raw.find("{") :])
    except (OSError, ValueError):
        return []
    hits = ((payload.get("data") or {}).get("hits") or []) if isinstance(payload, dict) else []
    return [hit for hit in hits if isinstance(hit, dict) and hit.get("watch")]


def plain(value) -> str:
    return _UNTRUSTED.sub("", str(value or "")).strip()


def feed_label(source) -> str:
    key = str(source or "")
    if "+" in key:  # a merged row names every feed that reported it
        return ", ".join(feed_label(part) for part in key.split("+"))
    if key in FEED_LABELS:
        return FEED_LABELS[key]
    return key.removeprefix("feed-").replace("-", " ").capitalize()


def watch_sections(hits: list[dict], text: list) -> str:
    out = ""
    titles = sorted(
        {plain(hit["watch"]) for hit in hits},
        key=lambda name: (DIGEST_GROUPS.index(name) if name in DIGEST_GROUPS else 99, name),
    )
    for title in titles:
        group = sorted(
            (hit for hit in hits if plain(hit["watch"]) == title),
            key=lambda hit: str(hit.get("published") or hit.get("seen") or ""),
            reverse=True,
        )
        # The digest ranks its rows, most urgent first. A stable sort keeps date order within
        # a rank, and rows with no rank (a user's own watch) stay in date order.
        group.sort(key=lambda hit: hit["rank"] if isinstance(hit.get("rank"), int) else 10**6)
        inner = ""
        text.append(title.upper())
        for hit in group:
            url = str(hit.get("url") or "")
            name = esc(plain(hit.get("value")))
            if url.startswith("https://") and not any(ch.isspace() for ch in url):
                name = (
                    f'<a href="{esc(url)}" style="color:#0b2545;text-decoration:none;">{name}</a>'
                )
            day = str(hit.get("published") or hit.get("seen") or "")[:10]
            source = feed_label(hit.get("source"))
            inner += (
                '<table role="presentation" width="100%" cellpadding="0" cellspacing="0" '
                'style="border-left:3px solid'
                ' #6d28d9;background:#ede9fe;border-radius:4px;margin-bottom:8px;">'
                '<tr><td style="padding:10px 12px;"><div'
                f' style="font-size:15px;font-weight:700;">{name}</div>'
                f'<div style="font-size:12px;color:#6b7280;margin-top:2px;">{esc(source)} &middot;'
                f" {esc(day)}</div>"
                "</td></tr></table>"
            )
            text.append(f"- {plain(hit.get('value'))} ({source}, {day})")
            if url:
                text.append(f"    {url}")
        note = (
            "New in the public vulnerability feeds since the last briefing."
            if title in DIGEST_GROUPS
            else "Matched by a watch over public feeds."
        )
        inner += p(
            f"{note} Feed text is untrusted; read the source before acting.",
            size=12,
            colour="#6b7280",
        )
        text.append("")
        out += section(title, "#6d28d9", inner)
    return out


WEAK = ("stale", "partial", "unavailable")


def status_banner(data: dict, text: list) -> str:
    """Name sources that were stale or unreachable, so 'nothing new' is not read as confirmed."""
    weak = [
        row
        for row in data.get("coverage") or []
        if isinstance(row, dict) and str(row.get("status", "")).lower() in WEAK
    ]
    if not weak:
        return ""
    names = ", ".join(f"{row.get('name')} ({str(row.get('status')).lower()})" for row in weak)
    note = (
        f"Some sources were stale or unreachable: {names}."
        " A quiet result from them does not mean nothing was published."
    )
    text += [note, ""]
    return (
        '<tr><td style="padding:16px 28px 0;"><div style="background:#fffbeb;border:1px solid'
        " #fcd34d;border-radius:4px;padding:10px 14px;font-size:13px;line-height:1.5;"
        'color:#92400e;">'
        f"{esc(note)}</div></td></tr>"
    )


def counts(data: dict, watches: list[dict]) -> dict:
    coverage = [r for r in data.get("coverage") or [] if isinstance(r, dict)]
    return {
        "act": len((data.get("act_today") or {}).get("items") or []),
        "acsc": len([i for i in data.get("acsc") or [] if isinstance(i, dict)]),
        "watches": len(watches),
        "checked": sum(1 for r in coverage if str(r.get("status", "")).lower() == "checked"),
        "sources": len(coverage),
    }


def glance(tally: dict, text: list) -> str:
    cells = [
        ("To act on today", tally["act"], "#b91c1c"),
        ("New from ASD's ACSC", tally["acsc"], "#0b2545"),
        ("Watch hits", tally["watches"], "#6d28d9"),
    ]
    if tally["sources"]:
        cells.append(("Sources checked", f"{tally['checked']}/{tally['sources']}", "#374151"))
    text.append(" | ".join(f"{label}: {value}" for label, value, _c in cells))
    text.append("")
    tds = "".join(
        f'<td align="center" style="padding:10px 4px;width:{100 // len(cells)}%;">'
        f'<div style="font-size:22px;font-weight:700;color:{colour};">{esc(str(value))}</div>'
        f'<div style="font-size:11px;color:#6b7280;text-transform:uppercase;letter-spacing:0.5px;">'
        f"{esc(label)}</div></td>"
        for label, value, colour in cells
    )
    return (
        '<tr><td style="padding:16px 28px 0;"><table role="presentation" width="100%"'
        ' cellpadding="0" cellspacing="0" style="border:1px solid #e5e7eb;border-radius:6px;">'
        f"<tr>{tds}</tr></table></td></tr>"
    )


# Reporting clocks shown in the footer, from the au-regulatory connector's reviewed snapshot.
CLOCK_LABELS = {
    ("soci", "critical_incident"): "SOCI critical cyber incident",
    ("soci", "other_incident"): "SOCI other cyber incident",
    ("ransomware_payment", "payment"): "Ransomware payment report",
    ("ndb", "suspected_breach"): "NDB suspected breach assessment",
}
ASD_REPORT = "https://www.cyber.gov.au/report-a-cyber-security-incident"


def load_obligations(path: str | None) -> dict | None:
    if not path:
        return None
    try:
        data = json.loads(Path(path).read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None
    return data if isinstance(data, dict) and isinstance(data.get("obligations"), list) else None


def obligations_section(snapshot: dict | None, text: list) -> str:
    """The first fixed clock of each known obligation. Nothing is typed from memory."""
    if not snapshot:
        return ""
    rows, lines = "", []
    for item in snapshot["obligations"]:
        if not isinstance(item, dict):
            continue
        label = CLOCK_LABELS.get((item.get("regime"), item.get("trigger")))
        clock = next((c for c in item.get("clocks") or [] if c.get("hours") or c.get("days")), None)
        if not label or not clock:
            continue
        span = f"{clock['hours']} hours" if clock.get("hours") else f"{clock['days']} days"
        link = str(item.get("guidance_url") or "")
        cite = esc(item.get("citation"))
        if link.startswith("https://"):
            cite = f'<a href="{esc(link)}" style="color:#1d4ed8;">{cite}</a>'
        rows += (
            '<tr><td style="padding:4px 8px 4px 0;font-weight:600;white-space:nowrap;">'
            f"{esc(span)}</td>"
            f'<td style="padding:4px 0;">{esc(label)} &middot; '
            f'<span style="color:#6b7280;">{cite}</span></td></tr>'
        )
        lines.append(f"- {span}: {label} ({item.get('citation')})")
    if not rows:
        return ""
    note = (
        f"Report a cyber security incident to ASD's ACSC at {ASD_REPORT} or 1300 CYBER1."
        " Clocks run from awareness unless the source says otherwise. From the reviewed"
        f" au-regulatory snapshot of {snapshot.get('retrieved_at')}. Guidance, not legal advice."
    )
    text += ["REPORTING CLOCKS", *lines, note, ""]
    return section(
        "Reporting clocks",
        "#374151",
        '<table role="presentation" cellpadding="0" cellspacing="0" style="font-size:13px;'
        f'line-height:1.4;color:#374151;">{rows}</table>' + p(note, size=12, colour="#6b7280"),
    )


def item_badges(item: dict) -> str:
    out = "".join(
        "<span"
        ' style="display:inline-block;background:#fee2e2;color:#991b1b;font-size:12px;font-wei'
        "ght:700;"
        f'padding:2px 8px;border-radius:10px;margin-right:4px;">{esc(i)}</span>'
        for i in item.get("ids") or []
    )
    for key, fg, bg in (("tag", "#374151", "#f3f4f6"), ("e8", "#1e3a8a", "#dbeafe")):
        if item.get(key):
            label = f"E8: {item[key]}" if key == "e8" else item[key]
            out += (
                f'<span style="display:inline-block;background:{bg};color:{fg};font-size:12px;'
                f'padding:2px 8px;border-radius:10px;margin-right:4px;">{esc(label)}</span>'
            )
    audience = [str(a) for a in item.get("audience") or [] if str(a).strip()]
    if audience:
        out += (
            '<span style="display:inline-block;background:#ecfdf5;color:#065f46;font-size:12px;'
            f'padding:2px 8px;border-radius:10px;">For: {esc(", ".join(audience))}</span>'
        )
    return out


def render(
    data: dict,
    date_label: str,
    watches: list[dict] | None = None,
    *,
    marking: str | None = None,
    obligations: dict | None = None,
) -> tuple[str, str]:
    watches = watches or []
    text = [f"Australian cyber briefing: {date_label}", data.get("window", ""), ""]
    if marking:
        text = [body_marking(marking), "", *text]
    body = [glance(counts(data, watches), text), status_banner(data, text)]
    body.append(
        '<tr><td style="padding:24px 28px 8px;"><table role="presentation" width="100%"'
        ' cellpadding="0" cellspacing="0" '
        'style="background:#eff6ff;border-left:4px solid #1d4ed8;border-radius:4px;"><tr><td'
        ' style="padding:14px 16px;">'
        "<div"
        ' style="font-size:12px;font-weight:700;text-transform:uppercase;letter-spacing:1px;color:'
        '#1d4ed8;">Headline</div>'
        '<p style="margin:6px 0'
        f' 0;font-size:15px;line-height:1.55;">{para(data["headline"])}</p></td></tr></table></td><'
        "/tr>"
    )
    text += ["HEADLINE", data["headline"], ""]

    act = data.get("act_today") or {}
    items = [i for i in act.get("items") or [] if isinstance(i, dict)]
    inner = p(act.get("intro", ""), colour="#4b5563") if act.get("intro") else ""
    text.append("ACT TODAY")
    if act.get("intro"):
        text.append(act["intro"])
    for item in items:
        badges = item_badges(item)
        inner += (
            '<table role="presentation" width="100%" cellpadding="0" cellspacing="0" '
            'style="border:1px solid #fecaca;border-radius:6px;margin-bottom:10px;"><tr><td'
            ' style="padding:12px 14px;">'
            f'<div style="font-size:15px;font-weight:700;">{esc(item.get("title"))}</div>'
            f'<div style="margin:4px 0;">{badges}</div>'
            "<div"
            ' style="font-size:14px;line-height:1.5;color:#374151;">'
            f"{para(item.get('summary', ''))}</div>"
            "</td></tr></table>"
        )
        extra = [str(item[k]) for k in ("tag",) if item.get(k)]
        if item.get("e8"):
            extra.append(f"E8: {item['e8']}")
        if item.get("audience"):
            extra.append("For: " + ", ".join(str(a) for a in item["audience"]))
        text.append(
            f"- {item.get('title')} ({', '.join(item.get('ids') or [])}): {item.get('summary', '')}"
            + (f" [{'; '.join(extra)}]" if extra else "")
        )
    for note in act.get("notes") or []:
        inner += p(note)
        text.append(note)
    if not items and not act.get("notes"):
        inner += p("Nothing needs action today from the sources checked.")
        text.append("Nothing needs action today from the sources checked.")
    body.append(section("Act today", "#b91c1c", inner))
    text.append("")

    body.append(acsc_section(data, text))
    if watches:
        body.append(watch_sections(watches, text))

    week = data.get("this_week") or []
    if week:
        body.append(section("This week", "#b45309", "".join(p(x) for x in week)))
        text += ["THIS WEEK", *week, ""]

    know = data.get("worth_knowing") or []
    if know:
        body.append(section("Worth knowing", "#1d4ed8", "".join(p(x) for x in know)))
        text += ["WORTH KNOWING", *know, ""]

    rows = ""
    coverage = data.get("coverage") or []
    for index, row in enumerate(coverage):
        status = str(row.get("status", "")).lower()
        colour = STATUS.get(status, "#374151")
        border = "border-bottom:1px solid #e5e7eb;" if index < len(coverage) - 1 else ""
        rows += (
            '<tr><td style="padding:8px'
            f' 10px;{border}width:42%;font-weight:600;">{esc(row.get("name"))}</td>'
            f'<td style="padding:8px 10px;{border}"><span style="color:{colour};font-weight:700;">'
            f"{esc(status.capitalize())}</span> &middot; {esc(row.get('detail'))}</td></tr>"
        )
    if rows:
        body.append(
            section(
                "Coverage",
                "#374151",
                '<table role="presentation" width="100%" cellpadding="0" cellspacing="0" '
                f'style="font-size:14px;border-collapse:collapse;">{rows}</table>',
            )
        )
        text.append("COVERAGE")
        text += [f"- {r.get('name')}: {r.get('status')} ({r.get('detail')})" for r in coverage]
        text.append("")

    srcs = ""
    text.append("SOURCES")
    for source in data.get("sources") or []:
        links = " &middot; ".join(
            f'<a href="{esc(link.get("url"))}"'
            f' style="color:#1d4ed8;">{esc(link.get("label") or link.get("url"))}</a>'
            for link in source.get("links") or []
            if str(link.get("url", "")).startswith("https://")
        )
        srcs += (
            '<p style="margin:0 0'
            f' 8px;font-size:13px;line-height:1.5;color:#374151;">[{esc(source.get("n"))}] '
            f"{esc(source.get('text'))}{'<br>' + links if links else ''}</p>"
        )
        text.append(f"[{source.get('n')}] {source.get('text')}")
        text += [f"    {link.get('url')}" for link in source.get("links") or []]
    if srcs:
        body.append(
            '<tr><td style="padding:20px 28px 8px;"><h2 style="margin:0 0'
            ' 8px;font-size:16px;color:#374151;">Sources</h2>'
            f"{srcs}</td></tr>"
        )
    body.append(obligations_section(obligations, text))
    if marking:
        text += ["", body_marking(marking)]
    page = shell(date_label, data.get("window", ""), "".join(body), data["headline"], marking)
    return page, "\n".join(text)


