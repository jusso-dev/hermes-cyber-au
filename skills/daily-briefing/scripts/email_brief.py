def section(title: str, colour: str, inner: str) -> str:
    return (
        '<tr><td style="padding:20px 28px 4px;"><h2 style="margin:0 0'
        f' 8px;font-size:18px;color:{colour};">'
        f"&#9679; {esc(title)}</h2>{inner}</td></tr>"
    )


def p(text: str, size: int = 14, colour: str = "#1f2937") -> str:
    style = f"margin:0 0 8px;font-size:{size}px;line-height:1.55;color:{colour};"
    return f'<p style="{style}">{para(text)}</p>'


ACSC_FEEDS = (
    ("alerts", "Alerts and warnings", "#b91c1c", "#fee2e2"),
    ("advisories", "Advisories", "#b45309", "#fef3c7"),
    ("threats", "Threats", "#7c2d12", "#ffedd5"),
    ("publications", "Publications", "#1d4ed8", "#dbeafe"),
    ("news", "News", "#047857", "#d1fae5"),
)


def acsc_section(data: dict, text: list) -> str:
    items = [i for i in data.get("acsc") or [] if isinstance(i, dict)]
    inner = ""
    text.append("ASD'S ACSC: ALERTS, ADVISORIES, PUBLICATIONS AND NEWS")
    for feed, label, colour, tint in ACSC_FEEDS:
        group = [i for i in items if str(i.get("feed", "")).lower() == feed]
        if not group:
            continue
        inner += (
            '<div style="margin:12px 0'
            " 6px;font-size:12px;font-weight:700;text-transform:uppercase;"
            f'letter-spacing:1px;color:{colour};">{esc(label)}</div>'
        )
        text.append(label.upper())
        for item in group:
            url = str(item.get("url") or "")
            title = esc(item.get("title"))
            if url.startswith("https://www.cyber.gov.au/"):
                title = (
                    f'<a href="{esc(url)}" style="color:#0b2545;text-decoration:none;">{title}</a>'
                )
            inner += (
                f'<table role="presentation" width="100%" cellpadding="0" cellspacing="0" '
                'style="border-left:3px solid'
                f' {colour};background:{tint};border-radius:4px;margin-bottom:8px;">'
                '<tr><td style="padding:10px 12px;"><div'
                f' style="font-size:15px;font-weight:700;">{title}</div>'
                '<div style="font-size:12px;color:#6b7280;margin:2px 0'
                f' 4px;">{esc(item.get("published"))}</div>'
                "<div"
                ' style="font-size:14px;line-height:1.5;color:#374151;">'
                f"{para(item.get('summary', ''))}</div>"
                "</td></tr></table>"
            )
            text.append(
                f"- {item.get('title')} ({item.get('published')}): {item.get('summary', '')}"
            )
            if url:
                text.append(f"    {url}")
    if not items:
        inner += p("No new ACSC alerts, advisories, threats, publications or news in this window.")
        text.append("No new ACSC items in this window.")
    recent = [i for i in data.get("acsc_recent") or [] if isinstance(i, dict)]
    if recent:
        labels = {feed: label for feed, label, _c, _t in ACSC_FEEDS}
        inner += (
            '<div style="margin:14px 0 6px;font-size:12px;font-weight:700;text-transform:uppercase;'
            'letter-spacing:1px;color:#6b7280;">Earlier this week</div><table role="presentation"'
            ' width="100%" '
            'cellpadding="0" cellspacing="0" style="font-size:14px;border-collapse:collapse;">'
        )
        text.append("EARLIER THIS WEEK")
        for item in recent:
            url = str(item.get("url") or "")
            title = esc(item.get("title"))
            if url.startswith("https://www.cyber.gov.au/"):
                title = f'<a href="{esc(url)}" style="color:#1d4ed8;">{title}</a>'
            feed = labels.get(str(item.get("feed", "")).lower(), esc(item.get("feed")))
            inner += (
                '<tr><td style="padding:6px 8px;border-bottom:1px solid'
                " #f3f4f6;white-space:nowrap;color:#6b7280;"
                f'font-size:12px;vertical-align:top;">{esc(item.get("published"))}</td>'
                f'<td style="padding:6px 8px;border-bottom:1px solid #f3f4f6;">{title} '
                f'<span style="color:#9ca3af;font-size:12px;">&middot; {esc(feed)}</span></td></tr>'
            )
            text.append(f"- {item.get('published')} {item.get('title')} ({item.get('feed')}) {url}")
        inner += "</table>"
    if data.get("acsc_note"):
        inner += p(data["acsc_note"], size=13, colour="#6b7280")
        text.append(data["acsc_note"])
    text.append("")
    return section("ASD's ACSC", "#0b2545", inner)


_UNTRUSTED = re.compile(r"<<untrusted source=[^>]*>>\s*|\s*<<end untrusted>>")
FEED_LABELS = {
    "feed-msrc-update-guide": "MSRC Security Update Guide",
    "feed-ms-security-blog": "Microsoft Security blog",
    "feed-azure-updates": "Azure updates",
    "feed-m365-roadmap": "Microsoft 365 roadmap",
    "feed-ms-sentinel-blog": "Microsoft Sentinel blog",
    "feed-ms-defender-xdr-blog": "Defender XDR blog",
    "feed-ms-defender-endpoint-blog": "Defender for Endpoint blog",
    "feed-ms-defender-cloud-blog": "Defender for Cloud blog",
}


def load_watches(path: str | None) -> list[dict]:
    """Watch hits from `cyberau-mcp store watchlist hits`. A missing or bad file is no hits."""
    if not path:
        return []
    try:
        raw = open(path, encoding="utf-8").read()
        payload = json.loads(raw[raw.find("{") :])
    except (OSError, ValueError):
        return []
    hits = ((payload.get("data") or {}).get("hits") or []) if isinstance(payload, dict) else []
    return [hit for hit in hits if isinstance(hit, dict) and hit.get("watch")]


def plain(value) -> str:
    return _UNTRUSTED.sub("", str(value or "")).strip()


def feed_label(source) -> str:
    key = str(source or "")
    if key in FEED_LABELS:
        return FEED_LABELS[key]
    return key.removeprefix("feed-").replace("-", " ").capitalize()


def watch_sections(hits: list[dict], text: list) -> str:
    out = ""
    for title in sorted({plain(hit["watch"]) for hit in hits}):
        group = sorted(
            (hit for hit in hits if plain(hit["watch"]) == title),
            key=lambda hit: str(hit.get("published") or hit.get("seen") or ""),
            reverse=True,
        )
        inner = ""
        text.append(title.upper())
        for hit in group:
            url = str(hit.get("url") or "")
            name = esc(plain(hit.get("value")))
            if url.startswith("https://") and not any(ch.isspace() for ch in url):
                name = (
                    f'<a href="{esc(url)}" style="color:#0b2545;text-decoration:none;">{name}</a>'
                )
            day = str(hit.get("published") or hit.get("seen") or "")[:10]
            source = feed_label(hit.get("source"))
            inner += (
                '<table role="presentation" width="100%" cellpadding="0" cellspacing="0" '
                'style="border-left:3px solid'
                ' #6d28d9;background:#ede9fe;border-radius:4px;margin-bottom:8px;">'
                '<tr><td style="padding:10px 12px;"><div'
                f' style="font-size:15px;font-weight:700;">{name}</div>'
                f'<div style="font-size:12px;color:#6b7280;margin-top:2px;">{esc(source)} &middot;'
                f" {esc(day)}</div>"
                "</td></tr></table>"
            )
            text.append(f"- {plain(hit.get('value'))} ({source}, {day})")
            if url:
                text.append(f"    {url}")
        inner += p(
            "Matched by a watch over public feeds. Feed text is untrusted; read the source before"
            " acting.",
            size=12,
            colour="#6b7280",
        )
        text.append("")
        out += section(title, "#6d28d9", inner)
    return out


def render(data: dict, date_label: str, watches: list[dict] | None = None) -> tuple[str, str]:
    body, text = [], [f"Australian cyber briefing: {date_label}", data.get("window", ""), ""]
    body.append(
        '<tr><td style="padding:24px 28px 8px;"><table role="presentation" width="100%"'
        ' cellpadding="0" cellspacing="0" '
        'style="background:#eff6ff;border-left:4px solid #1d4ed8;border-radius:4px;"><tr><td'
        ' style="padding:14px 16px;">'
        "<div"
        ' style="font-size:12px;font-weight:700;text-transform:uppercase;letter-spacing:1px;color:'
        '#1d4ed8;">Headline</div>'
        '<p style="margin:6px 0'
        f' 0;font-size:15px;line-height:1.55;">{para(data["headline"])}</p></td></tr></table></td><'
        "/tr>"
    )
    text += ["HEADLINE", data["headline"], ""]

    body.append(acsc_section(data, text))
    if watches:
        body.append(watch_sections(watches, text))

    act = data.get("act_today") or {}
    items = act.get("items") or []
    inner = p(act.get("intro", ""), colour="#4b5563") if act.get("intro") else ""
    text.append("ACT TODAY")
    if act.get("intro"):
        text.append(act["intro"])
    for item in items:
        badges = "".join(
            "<span"
            ' style="display:inline-block;background:#fee2e2;color:#991b1b;font-size:12px;font-wei'
            "ght:700;"
            f'padding:2px 8px;border-radius:10px;margin-right:4px;">{esc(i)}</span>'
            for i in item.get("ids") or []
        )
        if item.get("tag"):
            badges += (
                '<span style="display:inline-block;background:#f3f4f6;color:#374151;font-size:12px;'
                f'padding:2px 8px;border-radius:10px;">{esc(item["tag"])}</span>'
            )
        inner += (
            '<table role="presentation" width="100%" cellpadding="0" cellspacing="0" '
            'style="border:1px solid #fecaca;border-radius:6px;margin-bottom:10px;"><tr><td'
            ' style="padding:12px 14px;">'
            f'<div style="font-size:15px;font-weight:700;">{esc(item.get("title"))}</div>'
            f'<div style="margin:4px 0;">{badges}</div>'
            "<div"
            ' style="font-size:14px;line-height:1.5;color:#374151;">'
            f"{para(item.get('summary', ''))}</div>"
            "</td></tr></table>"
        )
        text.append(
            f"- {item.get('title')} ({', '.join(item.get('ids') or [])}): {item.get('summary', '')}"
        )
    for note in act.get("notes") or []:
        inner += p(note)
        text.append(note)
    if not items and not act.get("notes"):
        inner += p("Nothing needs action today from the sources checked.")
        text.append("Nothing needs action today from the sources checked.")
    body.append(section("Act today", "#b91c1c", inner))
    text.append("")

    week = data.get("this_week") or []
    if week:
        body.append(section("This week", "#b45309", "".join(p(x) for x in week)))
        text += ["THIS WEEK", *week, ""]

    know = data.get("worth_knowing") or []
    if know:
        body.append(section("Worth knowing", "#1d4ed8", "".join(p(x) for x in know)))
        text += ["WORTH KNOWING", *know, ""]

    rows = ""
    coverage = data.get("coverage") or []
    for index, row in enumerate(coverage):
        status = str(row.get("status", "")).lower()
        colour = STATUS.get(status, "#374151")
        border = "border-bottom:1px solid #e5e7eb;" if index < len(coverage) - 1 else ""
        rows += (
            '<tr><td style="padding:8px'
            f' 10px;{border}width:42%;font-weight:600;">{esc(row.get("name"))}</td>'
            f'<td style="padding:8px 10px;{border}"><span style="color:{colour};font-weight:700;">'
            f"{esc(status.capitalize())}</span> &middot; {esc(row.get('detail'))}</td></tr>"
        )
    if rows:
        body.append(
            section(
                "Coverage",
                "#374151",
                '<table role="presentation" width="100%" cellpadding="0" cellspacing="0" '
                f'style="font-size:14px;border-collapse:collapse;">{rows}</table>',
            )
        )
        text.append("COVERAGE")
        text += [f"- {r.get('name')}: {r.get('status')} ({r.get('detail')})" for r in coverage]
        text.append("")

    srcs = ""
    text.append("SOURCES")
    for source in data.get("sources") or []:
        links = " &middot; ".join(
            f'<a href="{esc(link.get("url"))}"'
            f' style="color:#1d4ed8;">{esc(link.get("label") or link.get("url"))}</a>'
            for link in source.get("links") or []
            if str(link.get("url", "")).startswith("https://")
        )
        srcs += (
            '<p style="margin:0 0'
            f' 8px;font-size:13px;line-height:1.5;color:#374151;">[{esc(source.get("n"))}] '
            f"{esc(source.get('text'))}{'<br>' + links if links else ''}</p>"
        )
        text.append(f"[{source.get('n')}] {source.get('text')}")
        text += [f"    {link.get('url')}" for link in source.get("links") or []]
    if srcs:
        body.append(
            '<tr><td style="padding:20px 28px 8px;"><h2 style="margin:0 0'
            ' 8px;font-size:16px;color:#374151;">Sources</h2>'
            f"{srcs}</td></tr>"
        )
    return shell(date_label, data.get("window", ""), "".join(body), data["headline"]), "\n".join(
        text
    )


def fallback(raw: str, date_label: str) -> tuple[str, str]:
    inner = (
        '<tr><td style="padding:24px 28px;"><p style="margin:0 0'
        ' 12px;font-size:13px;color:#b45309;">'
        "The briefing did not arrive in the structured format, so it is shown as written.</p>"
        "<div"
        f' style="white-space:pre-wrap;font-size:14px;line-height:1.55;">{esc(raw.strip())}</div></'
        "td></tr>"
    )
    return shell(date_label, "", inner, "Morning cyber briefing"), raw


CONFIG_KEYS = ("api_url", "from", "to")


def load_settings(path: str | Path) -> dict:
    """Read email.yaml: api_url, from, to (one address or a list), optional key_file."""
    import yaml

    file = Path(path)
    data = yaml.safe_load(file.read_text(encoding="utf-8")) or {}
    if not isinstance(data, dict):
        raise ValueError("email.yaml must be a mapping")
    missing = [key for key in CONFIG_KEYS if not data.get(key)]
    if missing:
        raise ValueError("email.yaml is missing " + ", ".join(missing))
    url = str(data["api_url"]).strip()
    if not url.startswith("https://") or any(ch.isspace() for ch in url):
        raise ValueError("api_url must be an https URL")
    to = data["to"] if isinstance(data["to"], list) else [data["to"]]
    to = [str(item).strip() for item in to if str(item).strip()]
    if not to or any("@" not in item or any(ch.isspace() for ch in item) for item in to):
        raise ValueError("to must be one or more email addresses")
    key_file = Path(str(data.get("key_file") or "secrets/email-api-key"))
    if not key_file.is_absolute():
        key_file = file.parent / key_file
    return {"api_url": url, "from": str(data["from"]).strip(), "to": to, "key_file": key_file}


def read_key(path: Path) -> str:
    """The API key from a file only its owner can read. The value is never printed."""
    info = path.stat()
    if info.st_mode & (stat.S_IRWXG | stat.S_IRWXO):
        raise ValueError(f"{path.name} must be readable by its owner only (chmod 600)")
    key = path.read_text(encoding="utf-8").strip()
    if not key or any(ch.isspace() for ch in key):
        raise ValueError(f"{path.name} does not hold a usable key")
    return key


def send(settings: dict, subject: str, page: str, body: str, idempotency: str, post=None) -> str:
    """Send one message. Returns the provider's message id."""
    payload = {
        "from": settings["from"],
        "to": settings["to"],
        "subject": subject,
        "html": page,
        "text": body,
        "tags": [{"name": "edition", "value": "morning"}],
    }
    key = read_key(settings["key_file"])
    headers = {
        "Authorization": f"Bearer {key}",
        "Content-Type": "application/json",
        "Idempotency-Key": idempotency,
    }
    if post is None:
        import httpx

        def post(url, json_body, request_headers):
            response = httpx.post(
                url, json=json_body, headers=request_headers, timeout=60, follow_redirects=False
            )
            return response.status_code, response.text

    status, text = post(settings["api_url"], payload, headers)
    if status >= 300:
        # The key never reaches this message: only the status and a short body are kept.
        raise RuntimeError(f"email API answered {status}: {text[:120].replace(key, '[REDACTED]')}")
    try:
        ident = json.loads(text).get("id")
    except (ValueError, AttributeError):
        ident = None
    return str(ident or "sent")


def failure_page(date_label: str, reason: str) -> tuple[str, str]:
    note = (
        f"The morning briefing for {date_label} could not be generated ({reason}). "
        "Check the cron job output in Hermes: hermes -p cyber-au cron list."
    )
    inner = f'<tr><td style="padding:24px 28px;">{p(note)}</td></tr>'
    return shell(date_label, "", inner, "Morning briefing failed"), note + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Render or send the morning briefing email.")
    sub = parser.add_subparsers(dest="command", required=True)
    for name in ("render", "send"):
        cmd = sub.add_parser(name)
        cmd.add_argument("source", help="Model output holding the briefing JSON")
        cmd.add_argument("--date-label", required=True)
        cmd.add_argument("--watches", help="JSON from `cyberau-mcp store watchlist hits`")
        if name == "render":
            cmd.add_argument("--html", required=True)
            cmd.add_argument("--text", required=True)
        else:
            cmd.add_argument("--config", required=True, help="email.yaml")
            cmd.add_argument("--day", required=True, help="YYYY-MM-DD, for the idempotency key")
            cmd.add_argument("--failed", default="", help="Send a failure notice with this reason")
            cmd.add_argument(
                "--dry-run", action="store_true", help="Check settings and key, render, do not send"
            )
    args = parser.parse_args(argv)
    if args.command == "send" and args.failed:
        page, body = failure_page(args.date_label, args.failed)
        subject = f"Morning cyber briefing failed - {args.date_label}"
        suffix, shape = "failed", "failed"
    else:
        raw = open(args.source, encoding="utf-8").read()
        data = extract(raw)
        watches = load_watches(args.watches)
        page, body = (
            render(data, args.date_label, watches) if data else fallback(raw, args.date_label)
        )
        subject = f"Australian cyber briefing - {args.date_label}"
        suffix, shape = "brief", "structured" if data else "fallback"
    if args.command == "render":
        open(args.html, "w", encoding="utf-8").write(page)
        open(args.text, "w", encoding="utf-8").write(body)
        print(shape)
        return 0
    try:
        settings = load_settings(args.config)
        if args.dry_run:
            read_key(settings["key_file"])
            print(f"morning email ready ({shape}), not sent: dry run, {len(page)} bytes of HTML")
            return 0
        ident = send(settings, subject, page, body, f"cyberau-brief-{args.day}-{suffix}")
    except (OSError, ValueError, RuntimeError) as exc:
        print(f"morning email failed: {exc}")
        return 1
    print(f"morning email sent ({shape}): {ident}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
