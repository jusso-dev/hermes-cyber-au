"""Render the morning briefing JSON as an email and send it through an email API.

``render`` turns the model's briefing JSON (the shape asked for in
``references/email-prompt.txt``) and the intel store's watch hits into HTML and text.
``send`` renders, then posts one message to a Resend-compatible API (``POST`` JSON with
``from``, ``to``, ``subject``, ``html`` and ``text``, bearer key). Paperboy and Resend both
take that shape.

Every string from the model or a feed is HTML-escaped. Only https links are kept. If the
model output is not valid JSON, the raw text is wrapped in the same shell.

Settings live in the user-owned ``email.yaml`` in the profile data directory, never in
this repository. The API key is read from the file it names, sent once in a header, and
never printed.
"""

import argparse
import html
import json
import re
import stat
import sys
from pathlib import Path

STATUS = {
    "checked": "#15803d",
    "stale": "#b45309",
    "partial": "#b45309",
    "unavailable": "#6b7280",
    "not checked": "#6b7280",
}


def esc(value) -> str:
    return html.escape(str(value or ""), quote=True)


def para(text: str) -> str:
    out = esc(text)
    out = re.sub(r"^Proposal:", "<strong>Proposal:</strong>", out)
    return re.sub(r"(\[\d+(?:[-\u2013,]\s?\d+)*\])", r'<span style="color:#6b7280;">\1</span>', out)


def extract(raw: str):
    start, end = raw.find("{"), raw.rfind("}")
    if start == -1 or end <= start:
        return None
    try:
        data = json.loads(raw[start : end + 1])
    except json.JSONDecodeError:
        return None
    return data if isinstance(data, dict) and data.get("headline") else None


